import 'package:http/http.dart' as http;

import 'v2/request.dart';

/// Какая версия приложения выложена.
///
/// **Переехала в v2 раньше всего остального, и это порядок работ, а не вкус.**
/// Отсюда установленная копия узнаёт о новой версии; пока проверка жила в
/// первой версии API, её закрытие отняло бы у приложения способность узнать о
/// той самой версии, которая переводит его на вторую и меняет адрес сайта.
///
/// Ключ ручка не требует — сервер отвечает и без него, — но с ключом даёт
/// приложению порцию по устройству вместо общей анонимной по адресу: за одним
/// адресом оператора сидят десятки телефонов.
Future<http.Response> fetchVersion() => v2Get(v2Uri('/app/version'));
