import 'package:http/http.dart' as http;

import 'v2/request.dart';

/// Минимальная длина запроса. Столько же требует бекенд, но короткий запрос
/// отсекается ещё здесь: сервер отвечает на него отказом, а внятное сообщение
/// всё равно пришлось бы придумывать на стороне приложения.
const int minSearchQueryLength = 3;

/// Поиск не кэшируется: повторная ценность у запроса низкая, а ручка тяжёлая
/// (полнотекстовый поиск по всему собранию) и ограничена по частоте.
///
/// **Ключ здесь обязателен, и повторять анонимом нечего.** Раздел `search` —
/// единственный, которого анониму не полагается вовсе: второй запрос вернул бы
/// тот же отказ, зато общий ключ приложения оказался бы помечен негодным
/// из-за ручки, которая отвергла его не потому, что он плох.
Future<http.Response> searchString(String search) {
  return v2Get(
    v2Uri('/search', {'q': search}),
    retryAnonymously: false,
  );
}
