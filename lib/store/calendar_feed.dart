import 'package:shared_preferences/shared_preferences.dart';

import '../api/constants.dart';

/// ЧТО ЧЕЛОВЕК ПОДПИСАЛ В СВОЙ КАЛЕНДАРЬ.
///
/// Подписка живёт не у нас: календарь забирает ленту сам и в приложение больше
/// не заходит. Отсюда её слабое место, названное вебом прямо: **лента тихо
/// перестаёт обновляться, и человек этого не замечает месяцами** — ни ошибки,
/// ни пустого экрана, просто новых событий больше нет.
///
/// В октябре сайт переезжает на typikon.info, а старый адрес гаснет в середине
/// января: у всех, кто подписан на старый, лента и замолчит.
///
/// Достучаться до подписчика можно двумя путями, и они не заменяют друг друга.
/// Событием внутри самой ленты — это дело сервера и достаёт до всех, включая
/// подписчиков с сайта. И приложением: **тот, кто подписался из приложения,
/// приложение и открывает.** Второй путь есть только у нас, и он здесь.
///
/// Запоминаем не «подписан ли», а ЧТО именно подписано — адрес ленты на момент
/// подписки. Сравнение с нынешним и есть признак: разошлись — значит подписка
/// ведёт на прежний адрес. Никакой даты переезда в коде при этом не нужно, и в
/// день переезда править нечего.
const String _subscribedUrlKey = "calendarSubscribedUrl";

/// Подменяется тестом: в `flutter test` плагина хранилища нет.
Future<SharedPreferences> Function() readPrefs = SharedPreferences.getInstance;

void resetCalendarFeedStore() => readPrefs = SharedPreferences.getInstance;

/// Запомнить, что человек подписался на нынешний адрес.
Future<void> rememberCalendarSubscription() async {
  final prefs = await readPrefs();
  await prefs.setString(_subscribedUrlKey, calendarFeedUrl);
}

/// Адрес, который человек подписал. `null` — не подписывался из приложения.
Future<String?> subscribedCalendarUrl() async {
  final prefs = await readPrefs();
  return prefs.getString(_subscribedUrlKey);
}

/// Устарела ли подписка.
///
/// **Три состояния, а не два.** Не подписывался — предлагать нечего: человек мог
/// и не хотеть календаря вовсе, и звать его переподписаться было бы навязчиво.
/// Подписан на нынешний адрес — тем более молчим. Говорим только третьему.
///
/// Кто подписался до появления этой записи, сюда не попадёт: мы про него не
/// знаем. Его достаёт другой путь — событие в самой ленте.
bool subscriptionIsStale(String? subscribed) =>
    subscribed != null && subscribed.isNotEmpty && subscribed != calendarFeedUrl;
