/// Каким шрифтом рисовать текст певческого корпуса.
///
/// **Коды здесь не те, что у Библии.** У изданий Библии начертание зовётся `cu`
/// и `ro_cyr`, а корпус песнопений размечен своими: `cu_gr`, `ro`, `grc`, `en`,
/// `et`, `ar`. Взять `bibleFontFamily` значило бы промахнуться на всех до
/// единого.
///
/// **`cu_gr` — церковнославянский ГРАЖДАНКОЙ, а не уставом.** Различие видно
/// прямо в имени кода, и сайт его держит: уставный шрифт он даёт только `cu` и
/// `ro_cyr`. Приложение же до сих пор зашивало Monomakh во всякий показ
/// песнопения — то есть рисовало уставными буквами текст, набранный
/// гражданскими.
///
/// Проверено по самому корпусу, а не по догадке: во всех 123 227 строках `cu_gr`
/// нет ни одного уставного знака — ни титла (U+0483), ни звательца (U+0486), ни
/// узкого `ᲂ` (U+1C82), ни омеги, ни юса, ни ятя. Только гражданская кириллица с
/// ударениями, какую OldStandard рисует и без того.
///
/// Список разрешительный, как у Библии: незнакомое начертание получает
/// гражданский шрифт, а не уставный. Ошибиться в эту сторону дешевле — латиница
/// и греческий уставным шрифтом читаются хуже, чем церковнославянский
/// гражданским.
const String _churchFont = "Monomakh";
const String _civilFont = "OldStandard";

/// Начертания корпуса, которым нужен уставный шрифт.
///
/// Пусто по содержимому нынешнего корпуса: `content_items.language` знает только
/// `cu_gr`, `ro`, `grc`, `en`, `et`, `ar`. Но список не пуст, потому что коды
/// `cu` и `ro_cyr` в словаре языков проекта есть и приходят из Библии; заведут
/// такое издание в корпусе — оно нарисуется верно с первого дня.
const Set<String> _churchScripts = {"cu", "ro_cyr"};

String chantFontFamily(String? language) =>
    _churchScripts.contains(language) ? _churchFont : _civilFont;

/// Строки песнопения.
///
/// Косая черта в корпусе — не знак препинания, а **перевод строки**: ею книги
/// размечают строки песнопения, и на телефоне это разница между читаемым и
/// нечитаемым. Страница песнопения на сайте её режет, страницы канонов и
/// акафистов — нет; берём первое, оно новее и продуманнее.
///
/// Пустые куски выбрасываются: «сло́во, / / и҆ сло́во» дало бы пустую строку
/// посреди текста.
List<String> chantLines(String text) => text
    .split("/")
    .map((line) => line.trim())
    .where((line) => line.isNotEmpty)
    .toList();
