/// Аргумент маршрута "/reading".
///
/// Прежде он нёс за решёткой главу или границы зачала — «`<textId>#3`»,
/// «`<textId>#6:31-6:34`». Всё это относилось к Библии, а Библия с 2.1 живёт
/// своим разделом со своим адресом (`utils/bible_route.dart`), и странице текста
/// хвост больше не нужен.
///
/// Разбирать его тем не менее приходится: старый вид остался в заметках
/// (`notes_page` строил его для заметок на стих), и приходить он будет ещё долго.
/// Поэтому хвост молча отбрасывается, а не роняет экран.
String readingTextId(String raw) {
  final hash = raw.indexOf("#");
  return hash == -1 ? raw : raw.substring(0, hash);
}
