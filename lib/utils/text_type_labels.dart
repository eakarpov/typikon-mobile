// Подписи типов текстов.
//
// Сервер шлёт коды — `Teaching`, `Historic`, `Synaxarion`, — а русских слов к
// ним не шлёт: перечень закрыт и лежит в самом корпусе. Поэтому имена здесь, и
// всякий незнакомый код показывается **как есть**, а не прячется и не подменяется
// «прочим»: заведут в корпусе новый род текста — читатель увидит его
// непереведённым, но увидит.
//
// Тот же уговор, что в `place_labels.dart` и `singing_labels.dart`.
//
// Это род текста, а не жанр произведения: службы лежат как Teaching, молитвы
// встречаются и как Prayer, и как Teaching. Подписи потому нейтральные — род,
// а не литературный вид.

const Map<String, String> _types = {
  "Teaching": "Учительные",
  "Reference": "Справочные",
  "Praising": "Похвальные",
  "Historic": "Исторические",
  "Synaxarion": "Сказания",
  "Interpretation": "Толкования",
  "Prayer": "Молитвы",
  "Catechistic": "Катехизические",
};

String textTypeLabel(String? code) =>
    code == null || code.isEmpty ? "" : (_types[code] ?? code);
