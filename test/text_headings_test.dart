import 'package:flutter_test/flutter_test.dart';

import 'package:typikon/utils/text_headings.dart';

// Оглавление внутри одного длинного текста. Формы — только подтверждённые
// данными корпуса (см. шапку lib/utils/text_headings.dart): скобочные метки
// `[Среда:]`, `[Статия 3]`, маркер в начале абзаца `[Статія́ 2-я ...]\n...`,
// короткий заголовок главы жития «О ...», «Чу́до ...», летописное «В лѣто ...».

void main() {
  group("скобочные метки", () {
    test("метка целиком — заголовок без скобок", () {
      final headings = findTextHeadings([
        "Начало текста.",
        "[Среда:]",
        "Текст среды.",
        "[Статия 3]",
        "Текст статии.",
      ]);

      expect(headings.map((h) => h.paragraphIndex), [1, 3]);
      expect(headings.map((h) => h.title), ["Среда:", "Статия 3"]);
    });

    test("метка в начале абзаца, текст со следующей строки", () {
      final headings = findTextHeadings([
        "[Статія́ 2-я въ четверто́къ Вели́каго кано́на 5-я недѣ́ли 40-цы.]\nПла́чущися же на мѣ́стѣ, на не́мже стоя́хъ, узрѣ́хъ",
        "Обычный абзац.",
      ]);

      expect(headings.single.paragraphIndex, 0);
      expect(headings.single.title,
          "Статія́ 2-я въ четверто́къ Вели́каго кано́на 5-я недѣ́ли 40-цы.");
    });

    test("незакрытая скобка целиком — тоже заголовок", () {
      // Так наборщик оставил одну из меток «Жития Варлаама».
      final headings = findTextHeadings([
        "[Чу́до свята́го Варлаа́ма о ры́бѣ",
        "Текст чуда.",
      ]);

      expect(headings.single.title, "Чу́до свята́го Варлаа́ма о ры́бѣ");
    });

    test("длинный абзац со скобкой внутри — не заголовок", () {
      final headings = findTextHeadings([
        "Чу́до о воскреше́нии ме́ртваго [о́трока] бысть в городе том, и весть о нем разошлась по всей окрестной стране.",
      ]);

      expect(headings, isEmpty);
    });
  });

  group("заголовки глав житий", () {
    test("короткий абзац «О ...» без конечной точки", () {
      final headings = findTextHeadings([
        "Поне́же у́бо о́нѣм [пре́жде бы́вшим] вели́ким и боже́ственым муже́м.",
        "О рожде́нии блаже́ннаго Варлаа́ма",
        "Сего́ блаже́ннаго о́трока, о не́мже нам сло́во.",
        "О слѣпо́м",
        "О уто́пшем, его́же святы́й па́ки воскреси́:",
      ]);

      expect(headings.map((h) => h.paragraphIndex), [1, 3, 4]);
    });

    test("«Чу́до ...» и «И́но чу́до ...» — заголовки", () {
      final headings = findTextHeadings([
        "Чу́до свята́го о ры́бах",
        "И́но чу́до свята́го чудотво́рца Варлаа́ма",
        "Ино́е о бѣсну́ющемся",
      ]);

      expect(headings.length, 3);
    });

    test("обычный абзац со словом «статия» — не заголовок", () {
      final headings = findTextHeadings([
        "В этом тексте говорится о статии о чуде святого, и ещё много чего рассказано здесь словами.",
      ]);

      expect(headings, isEmpty);
    });

    test("длинный абзац на «О ...» — не заголовок", () {
      final headings = findTextHeadings([
        "О том, как устроен мир, написано уже много слов, и ещё больше слов будет написано здесь.",
      ]);

      expect(headings, isEmpty);
    });

    test("абзац с точкой в конце — не заголовок, даже короткий", () {
      final headings = findTextHeadings([
        "О чуде рыб.",
      ]);

      expect(headings, isEmpty);
    });
  });

  group("летописные годы", () {
    test("голый год — заголовок сам по себе", () {
      final headings = findTextHeadings([
        "По потопѣ бо 3-е сынове Ноеви роздѣлиша земьлю.",
        "В лѣто 6361.",
      ]);

      expect(headings.single.paragraphIndex, 1);
      expect(headings.single.title, "В лѣто 6361");
    });

    test("год с аннотацией — заголовок до точки", () {
      final headings = findTextHeadings([
        "В лѣто 6360, индикта 15, наченшю Михаилу цесарьствовати, нача ся прозывати Руская земля. О семъ бо у Мефодия бысть.",
      ]);

      expect(headings.single.title,
          "В лѣто 6360, индикта 15, наченшю Михаилу цесарьствовати");
    });

    test("год с длинной аннотацией — заголовок только год", () {
      final headings = findTextHeadings([
        "В лѣто 6366. Михаилъ цесарь изыде с вои берегом и моремъ на болъгары, и многая разорения учини тамо.",
      ]);

      expect(headings.single.title, "В лѣто 6366");
    });

    test("обычный абзац про год — не заголовок", () {
      final headings = findTextHeadings([
        "В лѣтописи сказано о том, что же случилось в те времена, и об этом тут написано довольно подробно и протяжно.",
      ]);

      expect(headings, isEmpty);
    });
  });

  test("пустой и простой текст без заголовков", () {
    expect(findTextHeadings(["", "Просто абзац.", "Ещё абзац."]), isEmpty);
  });
}
