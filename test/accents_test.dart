import 'package:flutter_test/flutter_test.dart';
import 'package:typikon/utils/accents.dart';

// Снятие знаков ударения. Нужно ради заметок: подсветка ищет точное совпадение
// строки, и машинное ударение в тексте отвязывает заметку молча — ни ошибки, ни
// следа, подсветка просто исчезает.

void main() {
  group("снятие", () {
    test("ударение снимается, буква остаётся", () {
      expect(stripAccents("сло́во"), "слово");
      expect(stripAccents("живота́"), "живота");
      expect(stripAccents("твою̀"), "твою");
    });

    test("все три знака: оксия, вария, камора", () {
      expect(stripAccents("сло́во"), "слово");
      expect(stripAccents("сло̀во"), "слово");
      expect(stripAccents("сло̑во"), "слово");
    });

    test("готовая буква со знаком раскладывается", () {
      // В наборе они встречаются наравне с разложенными, и одна и та же строка
      // бывает записана и так и так.
      expect(stripAccents("твоѐ"), "твое");
      expect(stripAccents("ѝже"), "иже");
    });

    test("титло и звательце не трогаются", () {
      // Они принадлежат самому письму и стоят в обеих строках одинаково; сняв
      // их, мы сравнивали бы не то, что видим.
      expect(stripAccents("бж҃їѧ"), "бж҃їѧ");
      expect(stripAccents("а҆́ще"), "а҆ще");
    });

    test("текст без знаков не меняется", () {
      expect(stripAccents("слово"), "слово");
      expect(stripAccents(""), "");
    });
  });

  group("дорога обратно", () {
    test("отрезок находится по книжному написанию в размеченном тексте", () {
      // Заметка заведена по книге, текст показан с ударениями.
      const text = "Прииди́те, поклони́мся Царе́ви";
      final found = findIgnoringAccents(text, "поклонимся")!;

      // Проверяем вырезанное, а не число: смещение зависит от того, сколько
      // знаков стоит раньше в строке, и хрупко к правке образца.
      expect(text.substring(found.$1, found.$2), "поклони́мся");
    });

    test("и наоборот: размеченная заметка находится в книжном тексте", () {
      // Заметка заведена при включённых ударениях, а показывают книгу.
      final found = findIgnoringAccents("Прииди́те, поклонимся Цареви", "поклони́мся")!;

      expect("Прииди́те, поклонимся Цареви".substring(found.$1, found.$2), "поклонимся");
    });

    test("знак у последней буквы входит в отрезок", () {
      // Конец берётся по началу следующей буквы: отрезок, кончившийся на самой
      // букве, оставил бы знак снаружи и подсветил бы слово не до конца.
      const text = "и живота́ вечнаго";
      final found = findIgnoringAccents(text, "живота")!;

      expect(text.substring(found.$1, found.$2), "живота́");
    });

    test("отрезок в самом конце строки закрывается", () {
      const text = "сло́во";
      final found = findIgnoringAccents(text, "слово")!;

      expect(text.substring(found.$1, found.$2), "сло́во");
    });

    test("поиск с места пропускает раннее вхождение", () {
      const text = "сло́во и сло́во";
      final second = findIgnoringAccents(text, "слово", 3)!;

      expect(second.$1, greaterThan(3));
      expect(text.substring(second.$1, second.$2), "сло́во");
    });

    test("не нашлось — говорим об этом, а не притворяемся", () {
      expect(findIgnoringAccents("сло́во", "камень"), isNull);
      expect(findIgnoringAccents("сло́во", ""), isNull);
    });
  });
}
